DECLARE
    v_provinces INTEGER;
    v_cantons INTEGER;
    v_parishes INTEGER;
BEGIN
    SELECT COUNT(*) FILTER (WHERE hierarchy_level = 1),
           COUNT(*) FILTER (WHERE hierarchy_level = 2),
           COUNT(*) FILTER (WHERE hierarchy_level = 3)
      INTO v_provinces, v_cantons, v_parishes
      FROM seed_ec_dpa;

    IF v_provinces <> 24 OR v_cantons <> 222 OR v_parishes <> 1310 THEN
        RAISE EXCEPTION
            'Invalid seed counts. provinces=%, cantons=%, parishes=%',
            v_provinces, v_cantons, v_parishes;
    END IF;

    IF EXISTS (
        SELECT 1
          FROM seed_ec_dpa child
          LEFT JOIN seed_ec_dpa parent
            ON parent.canonical_code = child.parent_code
         WHERE child.hierarchy_level > 1
           AND (
                parent.canonical_code IS NULL
                OR parent.hierarchy_level <> child.hierarchy_level - 1
           )
    ) THEN
        RAISE EXCEPTION 'The staged DPA hierarchy contains an invalid parent';
    END IF;
END
