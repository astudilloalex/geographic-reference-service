    version = public.administrative_division_names.version + 1;

-- --------------------------------------------------------------------------
-- Final integrity gate
-- --------------------------------------------------------------------------
DO $final_validation$
DECLARE
    v_types INTEGER;
    v_provinces INTEGER;
    v_cantons INTEGER;
    v_parishes INTEGER;
    v_identifiers INTEGER;
    v_names INTEGER;
BEGIN
    SELECT COUNT(*)
      INTO v_types
      FROM public.administrative_division_types
     WHERE country_id = '019f9fd7-ade6-79bb-93b9-848cdda34c19'::UUID
       AND status = 'ACTIVE';

    SELECT COUNT(*) FILTER (WHERE division_type.hierarchy_level = 1),
           COUNT(*) FILTER (WHERE division_type.hierarchy_level = 2),
           COUNT(*) FILTER (WHERE division_type.hierarchy_level = 3)
      INTO v_provinces, v_cantons, v_parishes
      FROM public.administrative_divisions division
      JOIN public.administrative_division_types division_type
        ON division_type.id = division.division_type_id
       AND division_type.country_id = division.country_id
     WHERE division.country_id = '019f9fd7-ade6-79bb-93b9-848cdda34c19'::UUID
       AND division.status = 'ACTIVE'
       AND division.canonical_code IN (SELECT canonical_code FROM seed_ec_dpa);

    SELECT COUNT(*)
      INTO v_identifiers
      FROM public.administrative_division_identifiers identifier
      JOIN seed_ec_dpa staged
        ON staged.canonical_code = identifier.identifier_value
     WHERE identifier.country_id = '019f9fd7-ade6-79bb-93b9-848cdda34c19'::UUID
       AND identifier.scheme_code = 'EC_INEC_DPA'
       AND identifier.status = 'ACTIVE';

    SELECT COUNT(*)
      INTO v_names
      FROM public.administrative_division_names division_name
      JOIN public.administrative_divisions division
        ON division.id = division_name.division_id
       AND division.country_id = division_name.country_id
      JOIN seed_ec_dpa staged
        ON staged.canonical_code = division.canonical_code
     WHERE division_name.country_id = '019f9fd7-ade6-79bb-93b9-848cdda34c19'::UUID
       AND division_name.language_tag = 'es-EC'
       AND division_name.name_type = 'COMMON'
       AND division_name.is_preferred;

    IF v_types < 3
       OR v_provinces <> 24
       OR v_cantons <> 222
       OR v_parishes <> 1310
       OR v_identifiers <> 1556
       OR v_names <> 1556 THEN
        RAISE EXCEPTION
            'Seed validation failed: types=%, provinces=%, cantons=%, parishes=%, identifiers=%, names=%',
            v_types, v_provinces, v_cantons, v_parishes, v_identifiers, v_names;
    END IF;
END
$final_validation$;

COMMIT;

